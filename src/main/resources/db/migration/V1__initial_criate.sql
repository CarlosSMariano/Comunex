-- ==========================================
-- SCRIPT DDL - ORACLE DATABASE
-- Descrição: Estrutura do banco de dados da
-- plataforma de conexão comunitária.
-- ==========================================


-- ==========================================
-- 1. TABELA: BAIRRO
-- Descrição: Armazena os bairros e suas
-- respectivas informações geográficas.
-- ==========================================

CREATE TABLE BAIRRO (
                        ID_BAIRRO NUMBER GENERATED BY DEFAULT AS IDENTITY, -- Identificador único do bairro.
                        NOME VARCHAR2(100) NOT NULL,                       -- Nome do bairro.
                        MUNICIPIO VARCHAR2(100) NOT NULL,                  -- Município onde o bairro está localizado.
                        ESTADO CHAR(2) NOT NULL,                           -- Sigla do estado.

                        CONSTRAINT PK_BAIRRO PRIMARY KEY (ID_BAIRRO)       -- Define a chave primária da tabela.
);


-- ==========================================
-- 2. TABELA: USUARIO
-- Descrição: Armazena os dados cadastrais
-- dos usuários da plataforma.
-- ==========================================

CREATE TABLE USUARIO (
                         ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY, -- Identificador único do usuário.
                         ID_BAIRRO NUMBER NOT NULL,                          -- Bairro ao qual o usuário pertence.
                         NOME VARCHAR2(120) NOT NULL,                        -- Nome completo do usuário.
                         EMAIL VARCHAR2(150) NOT NULL,                       -- E-mail utilizado para identificação.
                         SENHA VARCHAR2(255) NOT NULL,                       -- Senha armazenada de forma protegida.
                         DESCRICAO VARCHAR2(500),                            -- Descrição ou apresentação do usuário.
                         TIPO_PERFIL VARCHAR2(20) NOT NULL,                  -- Tipo de perfil do usuário.
                         DATA_CADASTRO DATE DEFAULT SYSDATE NOT NULL,        -- Data de cadastro do usuário.

                         CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),     -- Define a chave primária da tabela.

                         CONSTRAINT FK_USUARIO_BAIRRO                        -- Relaciona o usuário ao bairro.
                             FOREIGN KEY (ID_BAIRRO)
                                 REFERENCES BAIRRO(ID_BAIRRO),

                         CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),         -- Impede o cadastro de e-mails duplicados.

                         CONSTRAINT CK_USUARIO_TIPO                          -- Restringe os tipos de perfil permitidos.
                             CHECK (TIPO_PERFIL IN (
                                                    'MORADOR',
                                                    'ORGANIZACAO',
                                                    'ADMINISTRADOR'
                                 ))
);


-- ==========================================
-- 3. TABELA: CATEGORIA
-- Descrição: Armazena as categorias utilizadas
-- para classificar as publicações.
-- ==========================================

CREATE TABLE CATEGORIA (
                           ID_CATEGORIA NUMBER GENERATED BY DEFAULT AS IDENTITY, -- Identificador único da categoria.
                           NOME VARCHAR2(100) NOT NULL,                          -- Nome da categoria.
                           DESCRICAO VARCHAR2(300),                              -- Descrição da categoria.

                           CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),   -- Define a chave primária da tabela.

                           CONSTRAINT UK_CATEGORIA_NOME UNIQUE (NOME)            -- Impede categorias com nomes duplicados.
);


-- ==========================================
-- 4. TABELA: PUBLICACAO
-- Descrição: Armazena as publicações realizadas
-- pelos usuários na plataforma.
-- ==========================================

CREATE TABLE PUBLICACAO (
                            ID_PUBLICACAO NUMBER GENERATED BY DEFAULT AS IDENTITY, -- Identificador único da publicação.
                            ID_USUARIO NUMBER NOT NULL,                            -- Usuário responsável pela publicação.
                            ID_BAIRRO NUMBER NOT NULL,                             -- Bairro relacionado à publicação.
                            ID_CATEGORIA NUMBER NOT NULL,                          -- Categoria da publicação.
                            TITULO VARCHAR2(150) NOT NULL,                         -- Título da publicação.
                            DESCRICAO VARCHAR2(1000) NOT NULL,                     -- Descrição detalhada da publicação.
                            TIPO VARCHAR2(20) NOT NULL,                            -- Tipo de publicação.
                            MODALIDADE VARCHAR2(20),                               -- Modalidade de participação ou atendimento.
                            STATUS VARCHAR2(20) DEFAULT 'ATIVA' NOT NULL,          -- Situação atual da publicação.
                            LATITUDE NUMBER(9,6),                                  -- Coordenada geográfica de latitude.
                            LONGITUDE NUMBER(9,6),                                 -- Coordenada geográfica de longitude.
                            DATA_CRIACAO DATE DEFAULT SYSDATE NOT NULL,            -- Data de criação da publicação.

                            CONSTRAINT PK_PUBLICACAO PRIMARY KEY (ID_PUBLICACAO), -- Define a chave primária da tabela.

                            CONSTRAINT FK_PUBLICACAO_USUARIO                      -- Relaciona a publicação ao usuário responsável.
                                FOREIGN KEY (ID_USUARIO)
                                    REFERENCES USUARIO(ID_USUARIO),

                            CONSTRAINT FK_PUBLICACAO_BAIRRO                       -- Relaciona a publicação ao bairro.
                                FOREIGN KEY (ID_BAIRRO)
                                    REFERENCES BAIRRO(ID_BAIRRO),

                            CONSTRAINT FK_PUBLICACAO_CATEGORIA                    -- Relaciona a publicação à sua categoria.
                                FOREIGN KEY (ID_CATEGORIA)
                                    REFERENCES CATEGORIA(ID_CATEGORIA),

                            CONSTRAINT CK_PUBLICACAO_TIPO                         -- Restringe os tipos de publicação permitidos.
                                CHECK (TIPO IN (
                                                'NECESSIDADE',
                                                'POTENCIALIDADE',
                                                'EVENTO'
                                    )),

                            CONSTRAINT CK_PUBLICACAO_MODALIDADE                   -- Restringe as modalidades permitidas.
                                CHECK (
                                    MODALIDADE IN (
                                                   'GRATUITA',
                                                   'VOLUNTARIA',
                                                   'TROCA'
                                        )
                                        OR MODALIDADE IS NULL
                                    ),

                            CONSTRAINT CK_PUBLICACAO_STATUS                       -- Restringe os status permitidos.
                                CHECK (STATUS IN (
                                                  'ATIVA',
                                                  'ENCERRADA',
                                                  'REMOVIDA'
                                    ))
);


-- ==========================================
-- 5. TABELA: EVENTO
-- Descrição: Armazena informações específicas
-- dos eventos vinculados às publicações.
-- ==========================================

CREATE TABLE EVENTO (
                        ID_EVENTO NUMBER GENERATED BY DEFAULT AS IDENTITY, -- Identificador único do evento.
                        ID_PUBLICACAO NUMBER NOT NULL,                     -- Publicação relacionada ao evento.
                        DATA_EVENTO DATE NOT NULL,                         -- Data e horário do evento.
                        LOCAL_EVENTO VARCHAR2(200) NOT NULL,              -- Endereço ou local de realização do evento.

                        CONSTRAINT PK_EVENTO PRIMARY KEY (ID_EVENTO),      -- Define a chave primária da tabela.

                        CONSTRAINT FK_EVENTO_PUBLICACAO                    -- Relaciona o evento à publicação correspondente.
                            FOREIGN KEY (ID_PUBLICACAO)
                                REFERENCES PUBLICACAO(ID_PUBLICACAO),

                        CONSTRAINT UK_EVENTO_PUBLICACAO UNIQUE (ID_PUBLICACAO) -- Permite apenas um evento por publicação.
);


-- ==========================================
-- 6. TABELA: INTERESSE
-- Descrição: Registra o interesse dos usuários
-- nas publicações disponíveis.
-- ==========================================

CREATE TABLE INTERESSE (
                           ID_INTERESSE NUMBER GENERATED BY DEFAULT AS IDENTITY, -- Identificador único do interesse.
                           ID_USUARIO NUMBER NOT NULL,                           -- Usuário que demonstrou interesse.
                           ID_PUBLICACAO NUMBER NOT NULL,                        -- Publicação de interesse.
                           DATA_INTERESSE DATE DEFAULT SYSDATE NOT NULL,         -- Data em que o interesse foi registrado.
                           STATUS VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL,         -- Situação atual do interesse.

                           CONSTRAINT PK_INTERESSE PRIMARY KEY (ID_INTERESSE),  -- Define a chave primária da tabela.

                           CONSTRAINT FK_INTERESSE_USUARIO                      -- Relaciona o interesse ao usuário.
                               FOREIGN KEY (ID_USUARIO)
                                   REFERENCES USUARIO(ID_USUARIO),

                           CONSTRAINT FK_INTERESSE_PUBLICACAO                   -- Relaciona o interesse à publicação.
                               FOREIGN KEY (ID_PUBLICACAO)
                                   REFERENCES PUBLICACAO(ID_PUBLICACAO),

                           CONSTRAINT UK_INTERESSE                              -- Impede interesse duplicado do mesmo usuário na publicação.
                               UNIQUE (ID_USUARIO, ID_PUBLICACAO),

                           CONSTRAINT CK_INTERESSE_STATUS                       -- Restringe os status permitidos.
                               CHECK (STATUS IN ('ATIVO', 'CANCELADO'))
);


-- ==========================================
-- 7. TABELA: SOLICITACAO_CONTATO
-- Descrição: Registra as solicitações de contato
-- originadas a partir de um interesse.
-- ==========================================

CREATE TABLE SOLICITACAO_CONTATO (
                                     ID_SOLICITACAO NUMBER GENERATED BY DEFAULT AS IDENTITY, -- Identificador único da solicitação.
                                     ID_INTERESSE NUMBER NOT NULL,                           -- Interesse que originou a solicitação.
                                     DATA_SOLICITACAO DATE DEFAULT SYSDATE NOT NULL,         -- Data de criação da solicitação.
                                     STATUS VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL,        -- Situação atual da solicitação.
                                     MENSAGEM VARCHAR2(500),                                -- Mensagem enviada na solicitação.

                                     CONSTRAINT PK_SOLICITACAO PRIMARY KEY (ID_SOLICITACAO), -- Define a chave primária da tabela.

                                     CONSTRAINT FK_SOLICITACAO_INTERESSE                     -- Relaciona a solicitação ao interesse.
                                         FOREIGN KEY (ID_INTERESSE)
                                             REFERENCES INTERESSE(ID_INTERESSE),

                                     CONSTRAINT UK_SOLICITACAO_INTERESSE                     -- Permite apenas uma solicitação por interesse.
                                         UNIQUE (ID_INTERESSE),

                                     CONSTRAINT CK_SOLICITACAO_STATUS                       -- Restringe os status permitidos.
                                         CHECK (STATUS IN (
                                                           'PENDENTE',
                                                           'ACEITA',
                                                           'RECUSADA'
                                             ))
);


-- ==========================================
-- 8. TABELA: DENUNCIA
-- Descrição: Armazena denúncias realizadas
-- pelos usuários sobre publicações.
-- ==========================================

CREATE TABLE DENUNCIA (
                          ID_DENUNCIA NUMBER GENERATED BY DEFAULT AS IDENTITY, -- Identificador único da denúncia.
                          ID_USUARIO NUMBER NOT NULL,                          -- Usuário responsável pela denúncia.
                          ID_PUBLICACAO NUMBER NOT NULL,                       -- Publicação denunciada.
                          MOTIVO VARCHAR2(100) NOT NULL,                       -- Motivo principal da denúncia.
                          DESCRICAO VARCHAR2(500),                             -- Detalhamento da denúncia.
                          DATA_DENUNCIA DATE DEFAULT SYSDATE NOT NULL,         -- Data em que a denúncia foi registrada.
                          STATUS VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL,     -- Situação atual da denúncia.

                          CONSTRAINT PK_DENUNCIA PRIMARY KEY (ID_DENUNCIA),    -- Define a chave primária da tabela.

                          CONSTRAINT FK_DENUNCIA_USUARIO                       -- Relaciona a denúncia ao usuário denunciante.
                              FOREIGN KEY (ID_USUARIO)
                                  REFERENCES USUARIO(ID_USUARIO),

                          CONSTRAINT FK_DENUNCIA_PUBLICACAO                    -- Relaciona a denúncia à publicação denunciada.
                              FOREIGN KEY (ID_PUBLICACAO)
                                  REFERENCES PUBLICACAO(ID_PUBLICACAO),

                          CONSTRAINT UK_DENUNCIA                               -- Impede que o mesmo usuário denuncie duas vezes a mesma publicação.
                              UNIQUE (ID_USUARIO, ID_PUBLICACAO),

                          CONSTRAINT CK_DENUNCIA_STATUS                        -- Restringe os status permitidos.
                              CHECK (STATUS IN (
                                                'PENDENTE',
                                                'ANALISADA'
                                  ))
);


-- ==========================================
-- 9. TABELA: MODERACAO
-- Descrição: Registra as ações de moderação
-- realizadas pelos administradores.
-- ==========================================

CREATE TABLE MODERACAO (
                           ID_MODERACAO NUMBER GENERATED BY DEFAULT AS IDENTITY, -- Identificador único da moderação.
                           ID_DENUNCIA NUMBER NOT NULL,                          -- Denúncia submetida à moderação.
                           ID_ADMINISTRADOR NUMBER NOT NULL,                     -- Administrador responsável pela análise.
                           ACAO VARCHAR2(20) NOT NULL,                           -- Ação tomada pelo administrador.
                           OBSERVACAO VARCHAR2(500),                             -- Justificativa ou observação da moderação.
                           DATA_MODERACAO DATE DEFAULT SYSDATE NOT NULL,         -- Data em que a moderação foi realizada.

                           CONSTRAINT PK_MODERACAO PRIMARY KEY (ID_MODERACAO),  -- Define a chave primária da tabela.

                           CONSTRAINT FK_MODERACAO_DENUNCIA                     -- Relaciona a moderação à denúncia analisada.
                               FOREIGN KEY (ID_DENUNCIA)
                                   REFERENCES DENUNCIA(ID_DENUNCIA),

                           CONSTRAINT FK_MODERACAO_ADMIN                        -- Relaciona a moderação ao administrador responsável.
                               FOREIGN KEY (ID_ADMINISTRADOR)
                                   REFERENCES USUARIO(ID_USUARIO),

                           CONSTRAINT UK_MODERACAO_DENUNCIA                     -- Permite apenas uma moderação por denúncia.
                               UNIQUE (ID_DENUNCIA),

                           CONSTRAINT CK_MODERACAO_ACAO                         -- Restringe as ações de moderação permitidas.
                               CHECK (ACAO IN ('MANTER', 'REMOVER'))
);